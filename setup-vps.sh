#!/usr/bin/env bash

# ==============================================================================
# 🚀 اسکریپت نصب و راه‌اندازی خودکار ربات قیمت خودرو بر روی سرور مجازی (VPS)
# ==============================================================================
# این اسکریپت به صورت خودکار Node.js، متعلقات پروژه و PM2 را روی سرور شما نصب کرده
# و ربات را در پس‌زمینه به حالت همیشه روشن (Daemon) در می‌آورد تا با بستن ترمینال خاموش نشود.
# ==============================================================================

# رنگ‌بندی ترمینال
GREEN='\033[0;32m'
CYAN='\033[0;36m'
YELLOW='\033[1;33m'
RED='\033[0;31m'
NC='\033[0m' # No Color

echo -e "${CYAN}======================================================"
echo -e "   🚘 شروع فرآیند نصب ربات قیمت خودرو ایرانی روی سرور مجازی"
echo -e "======================================================${NC}"

# ۱. بررسی دسترسی روت
if [ "$EUID" -ne 0 ]; then
  echo -e "${YELLOW}⚠️ توجه: این اسکریپت بهتر است با دسترسی root اجرا شود. در حال ادامه...${NC}"
fi

# ۲. بروزرسانی مخازن لینوکس
echo -e "\n${YELLOW}🔄 ۱. در حال بروزرسانی لیست پکیج‌های لینوکس...${NC}"
apt-get update -y && apt-get upgrade -y

# ۳. بررسی و نصب Node.js اگر نصب نباشد
if ! command -v node &> /dev/null; then
  echo -e "\n${YELLOW}📦 ۲. Node.js یافت نشد. در حال نصب آخرین نسخه پایدار Node.js Lts...${NC}"
  curl -fsSL https://deb.nodesource.com/setup_20.x | bash -
  apt-get install -y nodejs build-essential
else
  NODE_VERSION=$(node -v)
  echo -e "\n${GREEN}✅ Node.js از قبل روی سرور نصب است: (${NODE_VERSION})${NC}"
fi

# ۴. بررسی نصب بودن Git
if ! command -v git &> /dev/null; then
  echo -e "\n${YELLOW}📦 در حال نصب ابزار Git...${NC}"
  apt-get install -y git
fi

# ۵. نصب پکیج‌های پروژه
echo -e "\n${YELLOW}🔌 ۳. در حال نصب ملزومات پروژه در سرور...${NC}"
npm install

# ۶. کامپایل پروژه برای پروداکشن
echo -e "\n${YELLOW}🏗️ ۴. در حال ساخت و بیلد نهایی پروژه...${NC}"
npm run build

# ۷. نصب و فعال‌سازی PM2 برای همیشه روشن ماندن سرویس
echo -e "\n${YELLOW}👑 ۵. در حال نصب مدیریت پروسه PM2 به صورت سراسری...${NC}"
npm install -g pm2

# دکمه توقف ربات قبلی اگر وجود داشته باشد
echo -e "\n${YELLOW}🔄 توقف بات‌های قبلی در PM2 در صورت وجود...${NC}"
pm2 delete iran-car-bot &> /dev/null || true

# ۸. شروع ربات با PM2
echo -e "\n${GREEN}🚀 ۶. در حال اجرای ربات در پس‌زمینه با PM2...${NC}"
# استفاده از tsx برای اجرای لوکال سرور در صورت نیاز، یا اجرای مستقیم بیلد پروژه
# با توجه به ساختار پروژه، اجرای دستور استارت بهترین گزینه است
pm2 start "npm run start" --name "iran-car-bot"

# ذخیره وضعیت پروسه‌ها و پیکربندی سیستم سرویس برای لود خودکار بعد از ریبوت سرور
echo -e "\n${YELLOW}💾 ۷. تنظیم روشن شدن خودکار ربات بعد از ریبوت سرور مجازی...${NC}"
pm2 save
pm2 startup | tail -n 1 > temp_startup.sh
if [ -s temp_startup.sh ]; then
  echo -e "${CYAN}در حال اجرای دستور استارت‌آپ سیستم کلود...${NC}"
  # اجرای دستور خروجی تولید شده توسط متد startup
  bash temp_startup.sh || true
  rm -f temp_startup.sh
fi

echo -e "\n${GREEN}======================================================"
echo -e "🎉 تبریک! ربات با موفقیت نصب و در پس‌زمینه فعال شد."
echo -e "حتی اگر اتصال خود را از سرور قطع کنید، ربات همیشه اجرا خواهد ماند."
echo -e "======================================================${NC}"

echo -e "\n${CYAN}📋 دستورات کاربردی مدیریت ربات با PM2:${NC}"
echo -e "  🔹 مشاهده وضعیت ربات:      ${GREEN}pm2 status${NC}"
echo -e "  🔹 مشاهده لاگ‌ها به صورت زنده: ${GREEN}pm2 logs iran-car-bot${NC}"
echo -e "  🔹 ریستارت کردن ربات:      ${GREEN}pm2 restart iran-car-bot${NC}"
echo -e "  🔹 متوقف کردن ربات:        ${GREEN}pm2 stop iran-car-bot${NC}"
echo -e "======================================================"
